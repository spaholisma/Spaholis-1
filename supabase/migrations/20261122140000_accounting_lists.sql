-- Contabilidad: the dropdown lists of the Excel, editable from Contabilidad →
-- Listas. Same lists as the Excel's dropdowns:
--   treatment  ← sheet "Treatments" (with its categories) + "puntos terap"
--                (points per treatment for the therapists)
--   therapist  ← sheet "Staff"          pct ← the COMM % list (Staff A29:A43)
--   hotel      ← sheet "Vendor Commissions" (+ the usual % each one gets)
--   tl         ← Tourist / Local (the Excel's "Tourist-Local" sheet no longer exists)
--   purchase_category ← sheet "Purchases" (for the expenses, next step)
-- Full admins only, like the rest of Contabilidad.

create table if not exists public.accounting_lists (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('treatment', 'therapist', 'hotel', 'pct', 'tl', 'purchase_category')),
  label text not null check (length(btrim(label)) > 0),
  category text,                 -- treatments: MASSAGE + HOLISTIC, FACIALS…
  points numeric(4, 1),          -- treatments: therapist points
  default_pct numeric(6, 2) check (default_pct is null or (default_pct >= 0 and default_pct <= 100)), -- hotels: usual commission %
  sort_order integer not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists accounting_lists_kind_label_idx on public.accounting_lists (kind, lower(btrim(label)));

alter table public.accounting_lists enable row level security;
drop policy if exists accounting_lists_admin on public.accounting_lists;
create policy accounting_lists_admin on public.accounting_lists for all
  using (public.has_role(auth.uid(), 'super_admin') or public.has_role(auth.uid(), 'manager'))
  with check (public.has_role(auth.uid(), 'super_admin') or public.has_role(auth.uid(), 'manager'));
revoke all on public.accounting_lists from anon, authenticated;
grant select, insert, update, delete on public.accounting_lists to authenticated;

