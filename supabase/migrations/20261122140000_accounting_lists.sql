-- The usual % of each hotel / villa: the one used most in what is already in
-- Contabilidad (ties → the higher one).
update public.accounting_lists l
set default_pct = m.pct
from (
  select distinct on (lower(btrim(hotel))) lower(btrim(hotel)) as h, hotel_pct as pct
  from public.accounting_entries
  where hotel is not null
  group by lower(btrim(hotel)), hotel_pct
  order by lower(btrim(hotel)), count(*) desc, hotel_pct desc
) m
where l.kind = 'hotel' and lower(btrim(l.label)) = m.h and l.default_pct is null;
